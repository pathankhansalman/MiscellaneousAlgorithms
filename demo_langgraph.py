from typing import TypedDict
from transformers import AutoTokenizer, AutoModelForCausalLM
import torch
from langgraph.graph import StateGraph, START, END

# ---------------------------------------------------------------------------
# 1. MODEL SETUP
# Download and initialize a lightweight open-weights LLM locally from Hugging Face
# ---------------------------------------------------------------------------
MODEL_ID = "Qwen/Qwen2.5-0.5B"
tokenizer = AutoTokenizer.from_pretrained(MODEL_ID)
model = AutoModelForCausalLM.from_pretrained(MODEL_ID, torch_dtype=torch.float32)

# ---------------------------------------------------------------------------
# 2. STATE SCHEMA
# The central state object passed between nodes. Every node can read from
# this state and return a dict of keys to update/append.
# ---------------------------------------------------------------------------
class GraphState(TypedDict):
    prompt: str      # Input text provided to the graph
    next_word: str   # Generated by the model node
    word_len: int    # Computed by the tool node

# ---------------------------------------------------------------------------
# 3. NODES (Functions representing graph steps)
# ---------------------------------------------------------------------------
def generate_next_word(state: GraphState):
    """Node 1: Runs the LLM to predict the single next word following the prompt."""
    inputs = tokenizer(state["prompt"], return_tensors="pt")
    with torch.no_grad():
        output = model.generate(**inputs, max_new_tokens=1, pad_token_id=tokenizer.eos_token_id)
    next_token_id = output[0, inputs.input_ids.shape[-1]:]
    word = tokenizer.decode(next_token_id, skip_special_tokens=True).strip()
    return {"next_word": word}

def get_word_length_tool(state: GraphState):
    """Node 2 (Tool): Reads 'next_word' from state and computes its character length."""
    return {"word_len": len(state["next_word"])}

# ---------------------------------------------------------------------------
# 4. GRAPH CONSTRUCTION (Nodes & Edges)
# ---------------------------------------------------------------------------
builder = StateGraph(GraphState)

# Register the nodes
builder.add_node("model", generate_next_word)
builder.add_node("length_tool", get_word_length_tool)

# Define the control flow (edges):
# START -> model -> length_tool -> END
builder.add_edge(START, "model")
builder.add_edge("model", "length_tool")
builder.add_edge("length_tool", END)

# Compile the definition into a runnable graph executable
graph = builder.compile()

# ---------------------------------------------------------------------------
# 5. EXECUTION
# ---------------------------------------------------------------------------
sentence = "The capital of France is"
res = graph.invoke({"prompt": sentence})

print(f"Prompt: '{sentence}'")
print(f"Next Word: '{res['next_word']}'")
print(f"Word Length (from tool): {res['word_len']}")
